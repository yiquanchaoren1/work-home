import { cpSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(root, 'dist');
if (path.dirname(output) !== root || path.basename(output) !== 'dist') throw new Error('Invalid build destination');
rmSync(output, { recursive: true, force: true });
mkdirSync(output);
cpSync(path.join(root, 'public'), output, { recursive: true });
console.log(`Built ${readdirSync(output).length} static files into dist/`);
